import assert from 'node:assert/strict';
import {setTimeout as delay} from 'node:timers/promises';
const result=[];
globalThis.onmessage=null;
globalThis.postMessage=message=>result.push(message);
await import('../assets/nprimos/generator-worker.mjs');
const points=Array.from({length:65},(_,i)=>[i+1,(i+1)*2+5]);
globalThis.onmessage({data:{type:'start',points,config:{n:100,generational:true,maxTerms:2,maxX:1,constant:true,ranges:[{min:1,max:30},{min:31,max:65}]}}});
await delay(25);
globalThis.onmessage({data:{type:'pause'}});
assert.ok(result.some(item=>item.type==='paused'));
const first=result.filter(item=>item.type==='progress').at(-1)?.done||0;
assert.ok(first>=10);
await delay(25);
assert.equal(result.filter(item=>item.type==='progress').at(-1)?.done,first);
globalThis.onmessage({data:{type:'resume'}});
for(let i=0;i<90&&!result.some(item=>item.type==='complete');i++)await delay(20);
assert.ok(result.some(item=>item.type==='complete'),'worker should complete');
assert.equal(result.filter(item=>item.type==='complete')[0].done,100);
const rows=result.filter(item=>item.type==='progress').flatMap(item=>item.batch);
assert.ok(rows.length>0);assert.ok(rows.every(item=>item.model.terms.length<=2&&item.model.terms.every(t=>t.uses===1)));
assert.ok(rows.every(item=>item.ranges.length===2));
console.log('OK: Web Worker cede control, pausa/reanuda, progreso, historial y restricciones');
